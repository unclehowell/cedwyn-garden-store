#!/usr/bin/env python3
"""deploy.py - Garden Store (webapp 46 of 59): deploy worker/index.js + meta.js + catalogue.js (generated from catalogue.json)
+ images.js (generated from images.json)
as the Cloudflare Worker cedwyn-garden-store (SQLite-backed Durable Object GardenDB = the webapp's own DB) on the route
cedwyn.bucklerfamily.estate/garden-store*. The apex (bucklerfamily.estate/garden-store/) reaches it through bfe-apex-router,
which proxies to the cedwyn hostname; no apex route of its own. Undo rows: work/cf-rebalance/changes.json + deploys.log.
  TAB_TASK_ID=<id> timeout -k 5 600 python3 deploy.py "message" [--setup] [--routes]      - Sion's Tab agent"""
import json, os, sys, base64, datetime as dt
sys.path.insert(0, '/home/user/tab/work/agent-ready')
import deploy as AR
HERE = os.path.dirname(os.path.abspath(__file__)); W = os.path.join(HERE, 'worker')
ACCT, ZONE, CF = AR.ACCT, AR.ZONE, AR.CF
NAME = 'cedwyn-garden-store'; ROUTES = ['cedwyn.bucklerfamily.estate/garden-store*']
SP = os.path.join(HERE, 'deploy-state.json'); ST = json.load(open(SP)) if os.path.exists(SP) else {}
def save(): json.dump(ST, open(SP, 'w'), indent=1)
def call(method, path, body=None):
    req = {"toolkit": "cloudflare", "method": method, "url": CF + path}
    if body is not None: req["body"] = body
    r = AR.ca(req); res = r.get('result') or {}; b = res.get('body')
    if b is None and res.get('body_head'):
        try: b = json.loads(res['body_head'])
        except Exception: b = {'raw': res['body_head'][:800]}
    if isinstance(b, str):
        try: b = json.loads(b)
        except Exception: b = {'raw': b[:800]}
    return int(res.get('status') or 0), (b or {'raw': json.dumps(r)[:800]})
def log(what, rollback):
    P = '/home/user/tab/work/cf-rebalance/changes.json'
    try: ch = json.load(open(P))
    except Exception: ch = []
    ch.append({"at_utc": dt.datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ'), "by": "cedwyn-garden-store (work/garden-store/deploy.py)", "what": what, "rollback": rollback})
    json.dump(ch, open(P, 'w'), ensure_ascii=False, indent=1)
def gen_seed():
    c = json.load(open(os.path.join(HERE, 'catalogue.json')))
    open(os.path.join(W, 'catalogue.js'), 'w').write('// generated by deploy.py from catalogue.json (sync.py snapshot) - seed for the GardenDB Durable Object\nexport default '
        + json.dumps({"fetched": c['fetched'], "products": c['products']}, ensure_ascii=False, separators=(',', ':')) + ';\n')
def setup():
    if not ST.get('worker_id'):
        s, b = call('POST', f'/accounts/{ACCT}/workers/workers', {"name": NAME, "subdomain": {"enabled": False}, "observability": {"enabled": True}})
        print('worker', s, json.dumps(b)[:300]); ST['worker_id'] = b['result']['id']; save()
        log(f"Worker {NAME} created ({ST['worker_id']})", f"DELETE /accounts/{ACCT}/workers/scripts/{NAME}")
def gen_images():
    mp = json.load(open(os.path.join(HERE, 'images.json')))['map'] if os.path.exists(os.path.join(HERE, 'images.json')) else {}
    open(os.path.join(W, 'images.js'), 'w').write('// generated by deploy.py from images.json (images.py) - her CDN image URL -> hosted webp key\nexport default ' + json.dumps(mp, separators=(',', ':')) + ';\n')
def deploy(msg):
    gen_seed(); gen_images()
    mod = lambda n: {"name": n, "content_type": "application/javascript+module", "content_base64": base64.b64encode(open(os.path.join(W, n), 'rb').read()).decode()}
    binds = ([{"type": "durable_object_namespace", "name": "GARDEN", "class_name": "GardenDB"}] if ST.get('do_migrated') else []) + [{"type": "r2_bucket", "name": "IMG", "bucket_name": "wayback-media"}]  # 0.4.1: hosted webp photos under garden-store/img/
    b = {"compatibility_date": "2025-01-01", "main_module": "index.js", "modules": [mod('index.js'), mod('meta.js'), mod('catalogue.js'), mod('images.js')],
         "bindings": binds, **({"migrations": {"new_tag": "v1", "new_sqlite_classes": ["GardenDB"]}} if not ST.get('do_migrated') else {}), "annotations": {"workers/message": msg[:80]}}
    s, up = call('POST', f"/accounts/{ACCT}/workers/workers/{ST['worker_id']}/versions", b)
    if s not in (200, 201): print('version failed', s, json.dumps(up)[:1500]); sys.exit(1)
    vid = up['result']['id']
    s, dep = call('POST', f"/accounts/{ACCT}/workers/scripts/{NAME}/deployments", {"strategy": "percentage", "versions": [{"version_id": vid, "percentage": 100}], "annotations": {"workers/message": msg[:80]}})
    if s not in (200, 201): print('deploy failed', s, json.dumps(dep)[:1500]); sys.exit(1)
    prev = ST.get('version'); ST['previous'] = prev; ST['version'] = vid
    first = not ST.get('do_migrated'); ST['do_migrated'] = 'v1'; save()
    open(os.path.join(HERE, 'deploys.log'), 'a').write('%s deployed %s (previous %s): %s\n' % (dt.datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%SZ'), vid, prev, msg))
    log(f"{NAME}: version {vid} deployed 100%: {msg}", f"POST /accounts/{ACCT}/workers/scripts/{NAME}/deployments with version {prev}" if prev else f"DELETE /accounts/{ACCT}/workers/scripts/{NAME}")
    print(json.dumps({"version": vid, "previous": prev}))
    return first
def routes():
    ST.setdefault('routes', {})
    for pat in ROUTES:
        if pat in ST['routes']: continue
        s, b = call('POST', f'/zones/{ZONE}/workers/routes', {"pattern": pat, "script": NAME})
        print('route', pat, s, json.dumps(b)[:300])
        if s in (200, 201): ST['routes'][pat] = b['result']['id']; save(); log(f"route {pat} -> {NAME}", f"DELETE /zones/{ZONE}/workers/routes/{b['result']['id']}")
if __name__ == '__main__':
    if '--setup' in sys.argv: setup()
    first = deploy(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith('--') else 'cedwyn-garden-store update')
    if first: deploy('bind GardenDB')
    if '--setup' in sys.argv or '--routes' in sys.argv: routes()
